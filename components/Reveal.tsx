"use client";

import { useEffect, useRef, useState } from "react";

/**
 * Subtle reveal-on-scroll. CSS in globals.css disables the effect entirely
 * under prefers-reduced-motion; a <noscript> fallback in the root layout
 * keeps content visible without JavaScript.
 */
export default function Reveal({
  children,
  className = "",
}: {
  children: React.ReactNode;
  className?: string;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    // Under prefers-reduced-motion the CSS in globals.css shows content
    // unconditionally, so the observer is harmless there.
    const observer = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (entry.isIntersecting) {
            setVisible(true);
            observer.disconnect();
          }
        }
      },
      { threshold: 0.15, rootMargin: "0px 0px -40px 0px" }
    );
    observer.observe(el);
    return () => observer.disconnect();
  }, []);

  return (
    <div ref={ref} className={`reveal ${visible ? "is-visible" : ""} ${className}`}>
      {children}
    </div>
  );
}
